let current: Lang = "en";
try {
  const stored = localStorage.getItem("hymnix.lang");
  if (stored === "zh" || stored === "en") current = stored;
  else if ((navigator.language || "").toLowerCase().startsWith("zh")) current = "zh";
} catch { /* storage unavailable */ }

export function getLang(): Lang { return current; }
export function setLang(next: Lang): void { current = next; try { localStorage.setItem("hymnix.lang", next); } catch { /* ignore */ } }
export function t(text: string): string { return current === "zh" ? (zh[text] || text) : text; }
export function tf(template: string, values: any): string {
  const localized = t(template);
  return Object.keys(values).reduce((acc: string, key: string) => acc.split("{" + key + "}").join(values[key]), localized);
}

function translateText(raw: string): string {
  const trimmed = raw.trim();
  if (!trimmed) return raw;
  const direct = zh[trimmed];
  if (direct) return raw.replace(trimmed, direct);
  for (const pair of prefixes) {
    if (trimmed.indexOf(pair[0]) === 0) return pair[1] + trimmed.slice(pair[0].length);
  }
  return raw;
}

const ATTRS = ["placeholder", "title", "aria-label"];

export function translateDom(): void {
  if (current !== "zh") return;
  let translated = 0;
  (globalThis as any).__i18n = { translated: 0, lang: current };
  if (typeof document === "undefined" || !document.body) return;
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  const nodes: any[] = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  for (const node of nodes) {
    const parent = node.parentElement;
    if (!parent) continue;
    const tag = parent.tagName;
    if (tag === "SCRIPT" || tag === "STYLE" || tag === "TEXTAREA" || tag === "INPUT") continue;
    const next = translateText(node.nodeValue || "");
    if (next !== node.nodeValue) { node.nodeValue = next; translated++; (globalThis as any).__i18n.translated = translated; }
  }
  const elements: any[] = Array.from(document.body.querySelectorAll("*"));
  for (const element of elements) {
    for (const attr of ATTRS) {
      const value = element.getAttribute(attr);
      if (!value) continue;
      const next = translateText(value);
      if (next !== value) element.setAttribute(attr, next);
    }
  }
}

let observer: any = null;
export function installAutoTranslate(): void {
  translateDom();
  if (typeof MutationObserver === "undefined" || observer) return;
  observer = new MutationObserver(() => translateDom());
  observer.observe(document.body, { childList: true, subtree: true, characterData: true });
}