import { _electron as electron } from "@playwright/test";
import { resolve } from "node:path";
const cwd = resolve(process.cwd());
const env = { ...process.env };
delete env.ELECTRON_RUN_AS_NODE;
const app = await electron.launch({ args: ["--user-data-dir=C:\\Users\\xiaoy\\AppData\\Local\\Temp\\hymnix-risk", "."], cwd, env });
const win = await app.firstWindow();
await win.waitForFunction(() => Boolean(window.__hymnixDev), null, { timeout: 60000 });
await win.evaluate(() => { localStorage.setItem("hymnix.welcome","1"); localStorage.setItem("hymnix.whatsNew","1.4.0"); localStorage.setItem("hymnix.lang","zh"); });
await win.reload();
await win.waitForFunction(() => Boolean(window.__hymnixDev), null, { timeout: 60000 });
await win.setViewportSize({ width: 1440, height: 900 });
await win.evaluate(() => window.__hymnixDev.dismissOverlays());
for (let i = 0; i < 40; i += 1) { const boot = await win.evaluate(() => window.hymnix.bootstrap()); if (boot.ready) break; await win.waitForTimeout(500); }
await win.locator(".cb-chip.approval").click();
await win.waitForTimeout(400);
await win.evaluate(() => { const option = [...document.querySelectorAll(".policy-menu button")].find((el) => (el.textContent || "").includes("完全")); option?.click(); });
await win.waitForTimeout(700);
const policy = await win.evaluate(() => ({ open: Boolean(document.querySelector(".risk-dialog")), title: document.querySelector(".risk-dialog h3")?.textContent?.trim(), confirmDisabled: !!document.querySelector(".risk-dialog .btn.danger")?.disabled }));
console.log("POLICY_DIALOG " + JSON.stringify(policy));
await win.screenshot({ path: resolve(cwd, "../docs/audit-1.4.0/risk-policy.png") });
await win.locator(".risk-dialog .risk-ack input").check();
await win.waitForTimeout(200);
const enabled = await win.evaluate(() => !document.querySelector(".risk-dialog .btn.danger")?.disabled);
console.log("ACK_ENABLES_CONFIRM " + enabled);
await win.locator(".risk-dialog .btn").first().click();
await win.waitForTimeout(300);
console.log("CANCEL_CLOSES " + (await win.evaluate(() => !document.querySelector(".risk-dialog"))));
await app.close();
