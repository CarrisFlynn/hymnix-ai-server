import { _electron as electron } from "@playwright/test";
import { resolve } from "node:path";
const cwd = resolve(process.cwd());
const env = { ...process.env };
delete env.ELECTRON_RUN_AS_NODE;
const app = await electron.launch({ args: ["--user-data-dir=C:\\Users\\xiaoy\\AppData\\Local\\Temp\\hymnix-always10", "."], cwd, env });
const win = await app.firstWindow();
await win.waitForFunction(() => Boolean(window.__hymnixDev), null, { timeout: 60000 });
await win.evaluate(() => { localStorage.setItem("hymnix.welcome","1"); localStorage.setItem("hymnix.whatsNew","1.4.0"); localStorage.setItem("hymnix.lang","zh"); localStorage.removeItem("hymnix.approvals.always.v1"); });
await win.reload();
await win.waitForFunction(() => Boolean(window.__hymnixDev), null, { timeout: 60000 });
await win.setViewportSize({ width: 1440, height: 900 });
await win.evaluate(() => window.__hymnixDev.dismissOverlays());
for (let i = 0; i < 60; i += 1) { const boot = await win.evaluate(() => window.hymnix.bootstrap()); if (boot.ready) break; await win.waitForTimeout(500); }
await win.evaluate(() => { window.__hymnixDev.seedApprovals([{ id: "dbg-1", tool: "fs.write", risk: "moderate", reasons: ["writes a file"], argsRedacted: { path: "x.txt" }, createdAt: Date.now() }]); window.__hymnixDev.openApprovals(); });
await win.waitForTimeout(600);
console.log("BUTTONS " + JSON.stringify(await win.evaluate(() => [...document.querySelectorAll(".approval-row button")].map((el) => el.textContent?.trim()))));
console.log("DIALOG_BEFORE " + JSON.stringify(await win.evaluate(() => Boolean(document.querySelector(".risk-dialog")))));
await win.evaluate(() => { const b = [...document.querySelectorAll(".approval-row button")].find((el) => (el.textContent || "").trim() === "总是允许"); b?.click(); });
await win.waitForTimeout(800);
console.log("DIALOG_AFTER " + JSON.stringify(await win.evaluate(() => ({ open: Boolean(document.querySelector(".risk-dialog")), title: document.querySelector(".risk-dialog h3")?.textContent?.trim() ?? null }))));
await app.close();
