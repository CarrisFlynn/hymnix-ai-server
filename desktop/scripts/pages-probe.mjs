import { _electron as electron } from "@playwright/test";
import { resolve } from "node:path";
const cwd = resolve(process.cwd());
const env = { ...process.env };
delete env.ELECTRON_RUN_AS_NODE;
const app = await electron.launch({ args: ["--user-data-dir=C:\\Users\\xiaoy\\AppData\\Local\\Temp\\hymnix-ui2", "."], cwd, env });
const win = await app.firstWindow();
await win.waitForFunction(() => Boolean(window.__hymnixDev), null, { timeout: 60000 });
await win.evaluate(() => { localStorage.setItem("hymnix.welcome","1"); localStorage.setItem("hymnix.whatsNew","1.4.0"); localStorage.setItem("hymnix.lang","zh"); localStorage.setItem("hymnix.agents.v1", JSON.stringify({ reviewer: { name: "reviewer", system: "", messages: [{ role: "user", content: "检查 diff" }, { role: "assistant", content: "发现两处风险" }], updatedAt: Date.now() } })); });
await win.reload();
await win.waitForFunction(() => Boolean(window.__hymnixDev), null, { timeout: 60000 });
await win.setViewportSize({ width: 1440, height: 900 });
await win.evaluate(() => window.__hymnixDev.dismissOverlays());
for (let i = 0; i < 60; i += 1) { const boot = await win.evaluate(() => window.hymnix.bootstrap()); if (boot.ready) break; await win.waitForTimeout(500); }
await win.evaluate(() => window.__hymnixDev.navigate("Code"));
await win.waitForTimeout(600);
await win.evaluate(() => { const input = document.querySelector(".code-controls input"); if (input) { const setter = Object.getOwnPropertyDescriptor(window.HTMLInputElement.prototype, "value").set; setter.call(input, "streamTurn"); input.dispatchEvent(new Event("input", { bubbles: true })); } });
await win.waitForTimeout(300);
await win.evaluate(() => { const button = [...document.querySelectorAll(".code-controls button")].find((el) => (el.textContent || "").includes("查找定义")); button?.click(); });
await win.waitForTimeout(1500);
const code = await win.evaluate(() => ({ rows: document.querySelectorAll(".code-list li").length, first: document.querySelector(".code-list li code")?.textContent?.trim() }));
console.log("CODE_UI " + JSON.stringify(code));
await win.screenshot({ path: resolve(cwd, "../docs/audit-1.4.0/code-page.png") });
await win.evaluate(() => window.__hymnixDev.navigate("Agents"));
await win.waitForTimeout(600);
const agentsUi = await win.evaluate(() => ({ rows: document.querySelectorAll(".automation-row").length, first: document.querySelector(".automation-row strong")?.textContent?.trim() }));
console.log("AGENTS_UI " + JSON.stringify(agentsUi));
await win.screenshot({ path: resolve(cwd, "../docs/audit-1.4.0/agents-page.png") });
await app.close();
